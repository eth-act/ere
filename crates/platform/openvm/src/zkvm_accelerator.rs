#[unsafe(no_mangle)]
unsafe extern "C" fn zkvm_ripemd160(
    data: *const u8,
    len: usize,
    output: *mut zkvm_ripemd160_hash,
) -> zkvm_status {
    let digest = Ripemd160::digest(unsafe { slice::from_raw_parts(data, len) });
    // The C interface right-aligns the 20-byte digest in 32 bytes.
    let mut hash = [0u8; 32];
    hash[12..].copy_from_slice(&digest);
    unsafe { (*output).data = hash };
    ZKVM_EOK
}

#[unsafe(no_mangle)]
unsafe extern "C" fn zkvm_modexp(
    base: *const u8,
    base_len: usize,
    exp: *const u8,
    exp_len: usize,
    modulus: *const u8,
    mod_len: usize,
    output: *mut u8,
) -> zkvm_status {
    let (base, exp, modulus) = unsafe {
        (
            slice::from_raw_parts(base, base_len),
            slice::from_raw_parts(exp, exp_len),
            slice::from_raw_parts(modulus, mod_len),
        )
    };

    let result = if is_bn254_fr(modulus) {
        accelerated_modexp_bn254_fr(base, exp)
    } else {
        aurora_engine_modexp::modexp(base, exp, modulus)
    };

    // EIP-198 defines the output as exactly `mod_len` bytes, left-padded with zeros.
    let output = unsafe { slice::from_raw_parts_mut(output, mod_len) };
    let offset = mod_len - result.len();
    output[..offset].fill(0);
    output[offset..].copy_from_slice(&result);
    ZKVM_EOK
}

