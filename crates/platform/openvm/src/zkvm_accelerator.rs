#[unsafe(no_mangle)]
unsafe extern "C" fn zkvm_secp256k1_ecrecover(
    msg: *const zkvm_secp256k1_hash,
    sig: *const zkvm_secp256k1_signature,
    mut recid: u8,
    output: *mut zkvm_secp256k1_pubkey,
) -> zkvm_status {
    let (msg, sig) = unsafe { (&(*msg).data, &(*sig).data) };

    let Ok(mut signature) = Signature::from_slice(sig) else {
        return ZKVM_EFAIL;
    };

    if let Some(signature_normalized) = signature.normalize_s() {
        signature = signature_normalized;
        recid ^= 1;
    }

    let Some(recovery_id) = RecoveryId::from_byte(recid) else {
        return ZKVM_EFAIL;
    };

    let Ok(recovered_key) =
        VerifyingKey::recover_from_prehash_noverify(msg, &signature.to_bytes(), recovery_id)
    else {
        return ZKVM_EFAIL;
    };

    // The uncompressed SEC1 key without the `0x04` prefix.
    let public_key = recovered_key.to_encoded_point(false);
    unsafe { (*output).data = public_key.as_bytes()[1..65].try_into().unwrap() };
    ZKVM_EOK
}

