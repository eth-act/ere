#[unsafe(no_mangle)]
unsafe extern "C" fn zkvm_bls12_map_fp_to_g1(
    field_element: *const zkvm_bls12_381_fp,
    result: *mut zkvm_bls12_381_g1_point,
) -> zkvm_status {
    type Fp = <bls12_381::G1Projective as MapToCurve>::Field;

    let Some(field_element) = Fp::from_bytes(unsafe { &(*field_element).data }).into_option()
    else {
        return ZKVM_EFAIL;
    };

    let point = bls12_381::G1Projective::map_to_curve(&field_element).clear_h();
    unsafe { (*result).data = serialize_bls12_g1(&bls12_381::G1Affine::from(point)) };
    ZKVM_EOK
}

#[unsafe(no_mangle)]
unsafe extern "C" fn zkvm_bls12_map_fp2_to_g2(
    field_element: *const zkvm_bls12_381_fp2,
    result: *mut zkvm_bls12_381_g2_point,
) -> zkvm_status {
    type Fp = <bls12_381::G1Projective as MapToCurve>::Field;
    type Fp2 = <bls12_381::G2Projective as MapToCurve>::Field;

    let field_element = unsafe { &(*field_element).data };
    let Some(c0) = Fp::from_bytes(field_element[..BLS_FP_LEN].try_into().unwrap()).into_option()
    else {
        return ZKVM_EFAIL;
    };
    let Some(c1) = Fp::from_bytes(field_element[BLS_FP_LEN..].try_into().unwrap()).into_option()
    else {
        return ZKVM_EFAIL;
    };

    // The `bls12_381` SWU map sends `u = 0`, and only `u = 0`, to infinity, so the finite image
    // EIP-2537 expects is hardcoded.
    if bool::from(c0.is_zero()) && bool::from(c1.is_zero()) {
        unsafe { (*result).data = MAP_FP2_TO_G2_ZERO };
        return ZKVM_EOK;
    }

    let point = bls12_381::G2Projective::map_to_curve(&Fp2 { c0, c1 }).clear_h();
    unsafe { (*result).data = serialize_bls12_g2(&bls12_381::G2Affine::from(point)) };
    ZKVM_EOK
}

#[unsafe(no_mangle)]
unsafe extern "C" fn zkvm_secp256r1_verify(
    msg: *const zkvm_secp256r1_hash,
    sig: *const zkvm_secp256r1_signature,
    pubkey: *const zkvm_secp256r1_pubkey,
    verified: *mut bool,
) -> zkvm_status {
    unsafe { *verified = verify_secp256r1(&(*msg).data, &(*sig).data, &(*pubkey).data) };
    ZKVM_EOK
}

fn verify_secp256k1(msg: &[u8; 32], sig: &[u8; 64], pubkey: &[u8; 64]) -> bool {
    // `from_slice` rejects zero and non-canonical r/s scalars.
    let Ok(signature) = Signature::from_slice(sig) else {
        return false;
    };
    // Plain-ECDSA semantics accept high-s signatures while `verify_prehash` enforces the low-s
    // rule, so normalize first. `(r, n - s)` verifies exactly when `(r, s)` does.
    let signature = signature.normalize_s().unwrap_or(signature);

    // The C interface carries the uncompressed public key without the SEC1 `0x04` tag.
    let mut sec1 = [0u8; 65];
    sec1[0] = 0x04;
    sec1[1..].copy_from_slice(pubkey);
    let Ok(verifying_key) = VerifyingKey::from_sec1_bytes(&sec1) else {
        return false;
    };

    verifying_key.verify_prehash(msg, &signature).is_ok()
}

fn verify_secp256r1(msg: &[u8; 32], sig: &[u8; 64], pubkey: &[u8; 64]) -> bool {
    // `from_slice` rejects zero and non-canonical r/s scalars.
    let Ok(signature) = P256Signature::from_slice(sig) else {
        return false;
    };

    let encoded_point =
        EncodedPoint::from_affine_coordinates(pubkey[..32].into(), pubkey[32..].into(), false);
    let Ok(verifying_key) = P256VerifyingKey::from_encoded_point(&encoded_point) else {
        return false;
    };

    verifying_key.verify_prehash(msg, &signature).is_ok()
}

/// Returns true if the modulus (big-endian, possibly with leading zeros) equals BN254 Fr.
fn is_bn254_fr(modulus: &[u8]) -> bool {
    // Strip leading zeros
    let stripped = match modulus.iter().position(|&b| b != 0) {
        Some(i) => &modulus[i..],
        None => return false, // all zeros
    };
    // bn::Scalar::MODULUS is little-endian, so compare against the reversed input
    stripped.len() == BN_SCALAR_LEN
        && stripped
            .iter()
            .rev()
            .eq(bn::Scalar::MODULUS.as_ref().iter())
}

/// Accelerated modexp for BN254 Fr using field arithmetic intrinsics.
fn accelerated_modexp_bn254_fr(base: &[u8], exp: &[u8]) -> Vec<u8> {
    use openvm_ecc_guest::algebra::{ExpBytes, Reduce};

    // OpenVM's field reduction requires inputs to be aligned to the field byte size.
    let padded_len = base
        .len()
        .next_multiple_of(BN_SCALAR_LEN)
        .max(BN_SCALAR_LEN);
    let mut padded = vec![0u8; padded_len];
    padded[padded_len - base.len()..].copy_from_slice(base);
    let base_fr = bn::Scalar::reduce_be_bytes(&padded);

    base_fr.exp_bytes(true, exp).to_be_bytes().as_ref().to_vec()
}

#[inline]
fn read_bn_fq(input: &[u8]) -> Option<bn::Fp> {
    bn::Fp::from_be_bytes(input)
}

#[inline]
fn read_bn_fq2(input: &[u8]) -> Option<bn::Fp2> {
    let y = read_bn_fq(&input[..BN_FQ_LEN])?;
    let x = read_bn_fq(&input[BN_FQ_LEN..BN_FQ_LEN * 2])?;
    Some(bn::Fp2::new(x, y))
}

#[inline]
fn read_bn_g1_point(input: &[u8; BN_G1_LEN]) -> Option<bn::G1Affine> {
    let px = read_bn_fq(&input[..BN_FQ_LEN])?;
    let py = read_bn_fq(&input[BN_FQ_LEN..])?;
    // SAFETY: `read_bn_fq` produces canonical Fp elements. `from_xy` itself checks the curve
    // equation and returns `None` if `(px, py)` is not on the curve.
    let point = unsafe { bn::G1Affine::from_xy(px, py) }?;
    point.is_in_correct_subgroup().then_some(point)
}

#[inline]
fn read_bn_g2_point(input: &[u8; BN_G2_LEN]) -> Option<bn::G2Affine> {
    let c0 = read_bn_fq2(&input[..BN_G1_LEN])?;
    let c1 = read_bn_fq2(&input[BN_G1_LEN..])?;
    // SAFETY: `read_bn_fq2` produces canonical Fp2 elements. `from_xy` itself checks the curve
    // equation and returns `None` if `(c0, c1)` is not on the twist.
    let point = unsafe { bn::G2Affine::from_xy(c0, c1) }?;
    point.is_in_correct_subgroup().then_some(point)
}

#[inline]
fn encode_bn_g1_point(point: bn::G1Affine) -> [u8; BN_G1_LEN] {
    let mut output = [0u8; BN_G1_LEN];

    let x_bytes: &[u8] = point.x().as_le_bytes();
    let y_bytes: &[u8] = point.y().as_le_bytes();
    for i in 0..BN_FQ_LEN {
        output[i] = x_bytes[BN_FQ_LEN - 1 - i];
        output[i + BN_FQ_LEN] = y_bytes[BN_FQ_LEN - 1 - i];
    }
    output
}

