#[unsafe(no_mangle)]
unsafe extern "C" fn zkvm_bn254_pairing(
    pairs: *const zkvm_bn254_pairing_pair,
    num_pairs: usize,
    verified: *mut bool,
) -> zkvm_status {
    if num_pairs == 0 {
        unsafe { *verified = true };
        return ZKVM_EOK;
    }

    let mut g1_points = Vec::with_capacity(num_pairs);
    let mut g2_points = Vec::with_capacity(num_pairs);
    for pair in unsafe { slice::from_raw_parts(pairs, num_pairs) } {
        let Some(g1) = read_bn_g1_point(&pair.g1.data) else {
            return ZKVM_EFAIL;
        };
        let Some(g2) = read_bn_g2_point(&pair.g2.data) else {
            return ZKVM_EFAIL;
        };
        let (g1_x, g1_y) = g1.into_coords();
        let (g2_x, g2_y) = g2.into_coords();
        g1_points.push(AffinePoint::new(g1_x, g1_y));
        g2_points.push(AffinePoint::new(g2_x, g2_y));
    }

    unsafe { *verified = Bn254::pairing_check(&g1_points, &g2_points).is_ok() };
    ZKVM_EOK
}

#[unsafe(no_mangle)]
unsafe extern "C" fn zkvm_blake2f(
    rounds: u32,
    h: *mut zkvm_blake2f_state,
    m: *const zkvm_blake2f_message,
    t: *const zkvm_blake2f_offset,
    f: u8,
) -> zkvm_status {
    let mut state = [0u64; 8];
    let mut message = [0u64; 16];
    let mut offset = [0u64; 2];
    unsafe {
        read_u64_le(&(*h).data, &mut state);
        read_u64_le(&(*m).data, &mut message);
        read_u64_le(&(*t).data, &mut offset);
    }

    blake2::compress(rounds, &mut state, &message, &offset, f != 0);

    unsafe { write_u64_le(&state, &mut (*h).data) };
    ZKVM_EOK
}

#[unsafe(no_mangle)]
unsafe extern "C" fn zkvm_kzg_point_eval(
    commitment: *const zkvm_kzg_commitment,
    z: *const zkvm_kzg_field_element,
    y: *const zkvm_kzg_field_element,
    proof: *const zkvm_kzg_proof,
    verified: *mut bool,
) -> zkvm_status {
    // `from_slice` is the only constructor and rejects lengths other than its own.
    let (commitment, z, y, proof) = unsafe {
        (
            Bytes48::from_slice(&(*commitment).data).unwrap(),
            Bytes32::from_slice(&(*z).data).unwrap(),
            Bytes32::from_slice(&(*y).data).unwrap(),
            Bytes48::from_slice(&(*proof).data).unwrap(),
        )
    };

    let env = EnvKzgSettings::default();
    unsafe {
        *verified = matches!(
            KzgProof::verify_kzg_proof(&commitment, &z, &y, &proof, env.get()),
            Ok(true)
        )
    };
    ZKVM_EOK
}

#[unsafe(no_mangle)]
unsafe extern "C" fn zkvm_bls12_g1_add(
    p1: *const zkvm_bls12_381_g1_point,
    p2: *const zkvm_bls12_381_g1_point,
    result: *mut zkvm_bls12_381_g1_point,
) -> zkvm_status {
    // EIP-2537 G1ADD validates on-curve only, not subgroup membership.
    let Some(p1) = (unsafe { read_bls_g1_point_no_subgroup_check(&(*p1).data) }) else {
        return ZKVM_EFAIL;
    };
    let Some(p2) = (unsafe { read_bls_g1_point_no_subgroup_check(&(*p2).data) }) else {
        return ZKVM_EFAIL;
    };
    unsafe { (*result).data = encode_bls_g1_point(&(p1 + p2)) };
    ZKVM_EOK
}

#[unsafe(no_mangle)]
unsafe extern "C" fn zkvm_bls12_g1_msm(
    pairs: *const zkvm_bls12_381_g1_msm_pair,
    num_pairs: usize,
    result: *mut zkvm_bls12_381_g1_point,
) -> zkvm_status {
    if num_pairs == 0 {
        unsafe { (*result).data = [0u8; BLS_G1_LEN] };
        return ZKVM_EOK;
    }

    let mut points = Vec::with_capacity(num_pairs);
    let mut scalars = Vec::with_capacity(num_pairs);
    for pair in unsafe { slice::from_raw_parts(pairs, num_pairs) } {
        let Some(point) = read_bls_g1_point(&pair.point.data) else {
            return ZKVM_EFAIL;
        };
        points.push(point);
        scalars.push(read_bls_scalar(&pair.scalar.data));
    }

    unsafe { (*result).data = encode_bls_g1_point(&Bls12_381::msm(&scalars, &points)) };
    ZKVM_EOK
}

